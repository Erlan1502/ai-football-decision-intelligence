from typing import List, Optional, Dict, Any
from pydantic import BaseModel, Field


class KeyStrengthItem(BaseModel):
    metric: str
    percentile: float = Field(..., ge=0.0, le=100.0)
    shap_impact: str
    tactical_rationale: str


class RiskAssessmentItem(BaseModel):
    category: str = Field(..., description="Category of risk: tactical_adaptation, physical_intensity, financial")
    severity: str = Field(..., description="LOW, MEDIUM, or HIGH")
    details: str
    mitigation: str


class FinancialArbitrageSchema(BaseModel):
    star_target_price_eur: float
    recommended_analog_price_eur: float
    fair_market_value_eur: float
    expected_savings_eur: float
    projected_resale_profit_eur: float


class TransferDossierSchema(BaseModel):
    """
    Structured scouting transfer dossier generated by Gemini 3.8 Flash.
    Strictly validated by Pydantic v2.
    """
    target_player_name: str
    recommended_analog_name: str
    tactical_similarity_score: float = Field(..., ge=0.0, le=100.0)
    executive_summary: str
    financial_arbitrage: FinancialArbitrageSchema
    key_strengths: List[KeyStrengthItem]
    tactical_fit_analysis: str
    risks_and_mitigations: List[RiskAssessmentItem]
    verdict: str = Field(..., description="STRONG_BUY | BUY | HOLD | AVOID")
    confidence_level_pct: float = Field(default=90.0, ge=50.0, le=100.0)


class TransferDossierRequest(BaseModel):
    target_player_id: int
    analog_player_id: int
    custom_tactical_instructions: Optional[str] = None
